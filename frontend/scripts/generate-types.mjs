// Regenerates every type the frontend takes from the backend. Run with `npm run gen:types`
// after the backend API, the report schema or the correlation models change.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { compile } from 'json-schema-to-typescript'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const backend = resolve(root, '../soc-ai-analyst-sprint2')
const out = join(root, 'src/api/generated')
const banner = '// Generated by scripts/generate-types.mjs. Do not edit by hand.\n\n'

function backendPython() {
  if (process.env.SOC_PYTHON) return process.env.SOC_PYTHON
  const venv = ['.venv/Scripts/python.exe', '.venv/bin/python'].map((path) => join(backend, path))
  return venv.find((path) => existsSync(path)) ?? 'python'
}

// The OpenAPI document and the correlation model come straight from the backend code,
// so the backend's dependencies must be installed. See frontend/README.md.
const exported = execFileSync(
  backendPython(),
  [
    '-c',
    [
      'import json',
      'from app.main import app',
      'from app.schemas.investigation import CorrelationResult',
      'print(json.dumps({"openapi": app.openapi(), "correlation": CorrelationResult.model_json_schema()}))',
    ].join('\n'),
  ],
  { cwd: backend, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
)
const { openapi, correlation } = JSON.parse(exported)

mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'openapi.json'), JSON.stringify(openapi, null, 2) + '\n')
writeFileSync(join(out, 'intake.ts'), banner + astToString(await openapiTS(openapi)))

const options = { bannerComment: banner.trim(), additionalProperties: false, unreachableDefinitions: true }
const reportSchema = JSON.parse(
  readFileSync(join(backend, 'skills/soc-case-investigator/references/report-schema.json'), 'utf8'),
)
writeFileSync(join(out, 'report.ts'), await compile(reportSchema, 'InvestigationReport', options))
// Pydantic puts a title on every field, which would turn each one into its own type alias.
function withoutFieldTitles(schema, isRoot = true) {
  if (Array.isArray(schema)) return schema.map((item) => withoutFieldTitles(item, false))
  if (schema === null || typeof schema !== 'object') return schema
  return Object.fromEntries(
    Object.entries(schema)
      .filter(([key]) => isRoot || key !== 'title')
      .map(([key, value]) => [key, key === '$defs' ? keepDefinitionTitles(value) : withoutFieldTitles(value, false)]),
  )
}

function keepDefinitionTitles(definitions) {
  return Object.fromEntries(Object.entries(definitions).map(([name, value]) => [name, withoutFieldTitles(value)]))
}

writeFileSync(
  join(out, 'correlation.ts'),
  await compile(withoutFieldTitles(correlation), 'CorrelationResult', options),
)

console.log(`Types written to ${out}`)
